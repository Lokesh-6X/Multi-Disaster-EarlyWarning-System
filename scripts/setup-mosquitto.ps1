<#
.SYNOPSIS
  Mosquitto setup (design/14 §14.1.2 step 4, design/01 §1.3.1, DD11, DD109, M0.4).
.DESCRIPTION
  Writes config/mosquitto/conf.d/ews.conf and config/mosquitto/acl, creates the password file
  config/mosquitto/passwd (git-ignored) with users ingest, the kits and simulator, adds one
  include_dir line to the service's mosquitto.conf and restarts the mosquitto service.
  Passwords are generated once and kept in .env (ingest) and simulator/.env (kits, simulator);
  they are never printed. Running it again keeps existing passwords.
  -ConfigOnly writes ews.conf, acl and passwd only (no admin needed, service untouched).
#>
param(
    [string[]]$Kits = @('KIT-01'),
    [string]$SiteId = '+',          # the site_id once the site exists; '+' until then
    [int]$Port = 1883,
    [string]$PersistenceDir = 'C:\ProgramData\mosquitto\',
    [string]$ServiceConf = 'C:\Program Files\mosquitto\mosquitto.conf',
    [string]$ConfDir,               # default: <repo>\config\mosquitto
    [switch]$ConfigOnly
)
$ErrorActionPreference = 'Stop'
$repo = Split-Path $PSScriptRoot -Parent
if (-not $ConfDir) { $ConfDir = Join-Path $repo 'config\mosquitto' }
$confD = Join-Path $ConfDir 'conf.d'
$passwdFile = Join-Path $ConfDir 'passwd'
$aclFile = Join-Path $ConfDir 'acl'
$utf8 = New-Object Text.UTF8Encoding $false

if (-not $ConfigOnly) {
    $isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
    if (-not $isAdmin) { throw 'Run this script from an administrator PowerShell (it changes mosquitto.conf and restarts the service).' }
}
if (-not (Get-Command mosquitto_passwd -ErrorAction SilentlyContinue)) { throw 'mosquitto_passwd not found on PATH; see docs/setup-guide.md step 1.5.' }

function Read-EnvFile([string]$path) {
    $map = [ordered]@{}
    if (Test-Path $path) {
        foreach ($l in Get-Content $path) { if ($l -match '^([A-Za-z_][A-Za-z0-9_]*)=(.*)$') { $map[$Matches[1]] = $Matches[2] } }
    }
    $map
}
function Set-EnvValues([string]$path, [hashtable]$values) {
    $lines = @(if (Test-Path $path) { Get-Content $path })
    foreach ($key in $values.Keys) {
        $line = "$key=$($values[$key])"
        if ($lines | Where-Object { $_ -match "^$key=" }) {
            $lines = @($lines | ForEach-Object { if ($_ -match "^$key=") { $line } else { $_ } })
        } else {
            $lines += $line
        }
    }
    [IO.File]::WriteAllLines($path, [string[]]$lines, $utf8)
}
function New-Password {
    $chars = [char[]]'abcdefghijkmnopqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789'
    $bytes = New-Object byte[] 24
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    -join ($bytes | ForEach-Object { $chars[$_ % $chars.Length] })
}
function Get-OrNew($map, [string]$key) { if ($map[$key]) { $map[$key] } else { New-Password } }

# Passwords: ingest in the backend .env, kits and simulator in simulator/.env (01 §1.7.3)
$backendEnvPath = Join-Path $repo '.env'
$simEnvPath = Join-Path $repo 'simulator\.env'
New-Item -ItemType Directory -Force (Split-Path $simEnvPath) | Out-Null
$backendEnv = Read-EnvFile $backendEnvPath
$simEnv = Read-EnvFile $simEnvPath

$users = [ordered]@{ 'ingest' = Get-OrNew $backendEnv 'MQTT_INGEST_PASSWORD' }
$simValues = @{}
foreach ($kit in $Kits) {
    $key = 'MQTT_PASSWORD_' + ($kit -replace '[^A-Za-z0-9]', '_').ToUpper()
    $users[$kit] = Get-OrNew $simEnv $key
    $simValues[$key] = $users[$kit]
}
$users['simulator'] = Get-OrNew $simEnv 'MQTT_SIMULATOR_PASSWORD'
$simValues['MQTT_SIMULATOR_PASSWORD'] = $users['simulator']

# Password file (hashes only); -c on the first user starts a new file
New-Item -ItemType Directory -Force $confD | Out-Null
$first = $true
foreach ($u in $users.Keys) {
    $passwdArgs = @('-b')
    if ($first) { $passwdArgs = @('-c', '-b') }
    & mosquitto_passwd @passwdArgs $passwdFile $u $users[$u]
    if ($LASTEXITCODE -ne 0) { throw "mosquitto_passwd failed for user $u" }
    $first = $false
}
# mosquitto_passwd makes the file readable by the current user only, but the service runs as SYSTEM (S-1-5-18).
# Keep it private: no inherited rights, only the current user and SYSTEM (read).
$me = [Security.Principal.WindowsIdentity]::GetCurrent().User.Value
& icacls $passwdFile /inheritance:r /grant:r "*${me}:F" '*S-1-5-18:R' | Out-Null
if ($LASTEXITCODE -ne 0) { throw "icacls failed to give SYSTEM read access to $passwdFile" }

# ACL (DD11): each kit publishes only below its own topic; ingest only subscribes; only simulator writes sim/clock
$acl = @(
    '# Generated by scripts/setup-mosquitto.ps1 (design/01 section 1.3.1, DD11). Edit the script, not this file.'
    ''
    '# ingest: subscribe only'
    'user ingest'
    "topic read sites/$SiteId/kits/+/readings"
    "topic read sites/$SiteId/kits/+/status"
    'topic read sim/clock'
    ''
    '# simulator: the demo clock only (simulated kits log in with their kit users)'
    'user simulator'
    'topic write sim/clock'
)
foreach ($kit in $Kits) {
    $acl += ''
    $acl += "# ${kit}: its own readings and status (incl. the last will)"
    $acl += "user $kit"
    $acl += "topic write sites/$SiteId/kits/$kit/#"
}
[IO.File]::WriteAllLines($aclFile, [string[]]$acl, $utf8)

# Broker settings (DD11, DD109)
$conf = @(
    '# Generated by scripts/setup-mosquitto.ps1 (design/01 section 1.3.1, DD11, DD109). Edit the script, not this file.'
    "listener $Port"
    'allow_anonymous false'
    "password_file $passwdFile"
    "acl_file $aclFile"
    'persistence true'
    "persistence_location $PersistenceDir"
    '# 0 = no limit; the default of 1000 drops readings while ingest is down (DD109)'
    'max_queued_messages 0'
    '# a Windows service has no console: log to a file (and to stdout when run by hand)'
    "log_dest file $(Join-Path $PersistenceDir 'mosquitto.log')"
    'log_dest stdout'
    'log_timestamp_format %Y-%m-%dT%H:%M:%S'
)
[IO.File]::WriteAllLines((Join-Path $confD 'ews.conf'), [string[]]$conf, $utf8)
Write-Host "Wrote $confD\ews.conf, $aclFile and $passwdFile (users: $($users.Keys -join ', '))"

Set-EnvValues $backendEnvPath @{
    'MQTT_HOST' = 'localhost'; 'MQTT_PORT' = "$Port"
    'MQTT_INGEST_USER' = 'ingest'; 'MQTT_INGEST_PASSWORD' = $users['ingest']
}
Set-EnvValues $simEnvPath $simValues
Write-Host 'Passwords stored in .env and simulator\.env'

if ($ConfigOnly) { return }

# Service: one include_dir line in mosquitto.conf, persistence folder, restart
New-Item -ItemType Directory -Force $PersistenceDir | Out-Null
$include = "include_dir $confD"
$serviceLines = @(Get-Content $ServiceConf)
if ($serviceLines -notcontains $include) {
    Copy-Item $ServiceConf "$ServiceConf.bak-m0.4" -Force
    $serviceLines = @($serviceLines | Where-Object { $_ -notmatch '^\s*include_dir\s' }) + $include
    [IO.File]::WriteAllLines($ServiceConf, [string[]]$serviceLines, $utf8)
    Write-Host "Added to $ServiceConf : $include (backup: mosquitto.conf.bak-m0.4)"
}
Write-Host 'Restarting the mosquitto service ...'
Restart-Service mosquitto
try {
    (Get-Service mosquitto).WaitForStatus('Running', [TimeSpan]::FromSeconds(15))
} catch {
    $log = Join-Path $PersistenceDir 'mosquitto.log'
    if (Test-Path $log) { Write-Host "Last lines of ${log}:"; Get-Content $log -Tail 15 | Write-Host }
    throw "The mosquitto service did not start (state: $((Get-Service mosquitto).Status))."
}
Start-Sleep -Seconds 1
if (-not (Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue)) { throw "mosquitto is running but nothing listens on port $Port" }
Write-Host "Done: mosquitto listens on $Port with the ews settings."
